// tools/glyphs.mjs — keep src/data/glyphs.js in sync with the text the film can draw.
//
// Web fonts with CJK (Noto Serif/Sans TC, LXGW WenKai) are split into unicode-range slices that
// the browser loads lazily, the first time a glyph is drawn. main.js preloads every glyph in
// chapters.js / film.config.js before the first frame; this file adds every non-ASCII character
// used in src/ code (scene labels like 「示範工廠」, arrows, ×, —) so a fresh page never draws a
// frame with a fallback font (that breaks determinism and looks wrong in single shots).
//
// Called automatically by tools/browser.mjs (every shot / sheet / render / check) and
// tools/build.mjs. Run by hand:  node tools/glyphs.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DEFAULT = path.resolve(HERE, '..');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const f = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== 'audio') walk(f, out);
    } else if (e.name.endsWith('.js') && e.name !== 'glyphs.js') out.push(f);
  }
  return out;
}

/** Strip comments (roughly; strings that contain // are kept because the regex needs a preceding non-quote). */
function stripComments(s) {
  return s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:'"`\\])\/\/.*$/gm, '$1');
}

/** Rewrite src/data/glyphs.js if the set of non-ASCII characters in src/ changed. Returns the glyph string. */
export function syncGlyphs(root = ROOT_DEFAULT) {
  const src = path.join(root, 'src');
  const set = new Set();
  for (const f of walk(src)) {
    const text = stripComments(fs.readFileSync(f, 'utf8'));
    for (const ch of text) {
      const cp = ch.codePointAt(0);
      if (cp > 0x7f && !/\s/.test(ch)) set.add(ch);
    }
  }
  const glyphs = [...set].sort().join('');
  const out = path.join(src, 'data', 'glyphs.js');
  const body = `// src/data/glyphs.js — GENERATED by tools/glyphs.mjs (do not edit; it is rewritten by every tool run).\n// Every non-ASCII character used in src/ code, preloaded with the web fonts before the first frame.\nexport const GLYPHS = ${JSON.stringify(glyphs)};\n`;
  let old = '';
  try {
    old = fs.readFileSync(out, 'utf8');
  } catch (e) {
    /* first run */
  }
  if (old !== body) fs.writeFileSync(out, body);
  return glyphs;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const g = syncGlyphs();
  console.log(`src/data/glyphs.js: ${[...g].length} glyphs`);
}
